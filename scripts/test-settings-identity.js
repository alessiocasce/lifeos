import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createProfileUpgradeDatabase } from '../tests/workout/profileUpgradeDatabase.js';
import { applyCommunityMigration } from '../tests/workout/communityDatabase.js';
import { normalizeUsername } from '../src/utils/userSettingsIdentity.js';

const A = '11111111-1111-4111-8111-111111111111';
const B = '22222222-2222-4222-8222-222222222222';
const C = '33333333-3333-4333-8333-333333333333';
const D = '44444444-4444-4444-8444-444444444444';
const migration = 'supabase/migrations/20261108220000_settings_identity_defaults.sql';
const db = await createProfileUpgradeDatabase();
try {
  for (const suffix of ['training_profile_upgrade', 'username_only_cleanup', 'training_active_identity_media']) await applyCommunityMigration(db, suffix);
  await db.exec('alter table auth.users add column email_confirmed_at timestamptz, add column raw_user_meta_data jsonb;');
  await db.query('insert into auth.users(id,email_confirmed_at,raw_user_meta_data) values($1,now(),$3),($2,now(),$3)', [A, B, '{}']);
  const as = async (id, sql, params = []) => {
    await db.exec('reset role');
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id || '']);
    await db.exec(`set role ${id ? 'authenticated' : 'anon'}`);
    return db.query(sql, params);
  };
  await as(A, "select save_user_settings('Alpha_One','en',false,false)");
  await as(B, "select save_user_settings('BRAVO','it',true,false)");
  await as(A, "update user_profiles set avatar_path=$1 where user_id=$2", [`${A}/55555555-5555-4555-8555-555555555555.webp`, A]);
  const workout = (await as(B, "insert into workouts(name,performed_on,started_at,ended_at,notes) values('Preserved workout','2026-10-01','2026-10-01T10:00:00Z','2026-10-01T11:00:00Z','private') returning id")).rows[0].id;
  await as(B, "insert into workout_sets(workout_id,exercise,set_number,weight,reps,rpe,notes) values($1,'Private custom move',1,20,8,8.5,'private set')", [workout]);
  const before = (await as(A, 'select user_id,username,avatar_path,created_at from user_profiles order by user_id')).rows;
  const sourceBefore = (await as(B, 'select to_jsonb(w) source,(select jsonb_agg(s) from workout_sets s where s.workout_id=w.id) sets from workouts w where id=$1', [workout])).rows;
  const shareBefore = (await as(A, 'select id,author_id,title,performed_on,notes,sets from community_workout_shares')).rows;
  await db.exec('reset role');
  await db.transaction(async tx => tx.exec(fs.readFileSync(migration, 'utf8')));
  await db.query('insert into auth.users(id,email_confirmed_at,raw_user_meta_data) values($1,now(),$2)', [C, '{}']);
  let after = (await as(A, 'select user_id,username,avatar_path,created_at from user_profiles order by user_id')).rows;
  assert.deepEqual(after, before.map(row => ({ ...row, username: row.username.toLowerCase() })));
  assert.deepEqual((await as(B, 'select to_jsonb(w) source,(select jsonb_agg(s) from workout_sets s where s.workout_id=w.id) sets from workouts w where id=$1', [workout])).rows, sourceBefore);
  assert.deepEqual((await as(A, 'select id,author_id,title,performed_on,notes,sets from community_workout_shares')).rows, shareBefore);
  assert.deepEqual((await as(A, 'select language,workout_sharing,share_workout_notes from user_preferences')).rows, [{ language: 'en', workout_sharing: false, share_workout_notes: false }]);
  await as(A, "update user_profiles set username='ALPHA_RENAMED'");
  assert.equal((await as(A, 'select username from user_profiles where user_id=$1', [A])).rows[0].username, 'alpha_renamed');
  assert.equal((await as(B, "select user_id from user_profiles where lower(username)=lower('AlPhA_ReNaMeD')")).rows[0].user_id, A);
  await assert.rejects(as(B, "update user_profiles set username='ALPHA_RENAMED' where user_id=$1", [B]), /unique/);
  assert.equal((await as(A, "update user_profiles set username='hacked' where user_id=$1 returning user_id", [B])).rows.length, 0);
  assert.equal((await as(A, "update user_preferences set language='en' where user_id=$1 returning user_id", [B])).rows.length, 0);
  await as(C, "select complete_user_profile('CHARLIE')");
  assert.deepEqual((await as(C, 'select language,workout_sharing,share_workout_notes from user_preferences')).rows[0], { language: 'it', workout_sharing: true, share_workout_notes: false });
  assert.equal((await as(C, 'select username from user_profiles where user_id=$1', [C])).rows[0].username, 'charlie');
  await db.exec('reset role');
  await db.query('insert into auth.users(id,email_confirmed_at,raw_user_meta_data) values($1,now(),$2)', [D, '{"requested_language":"en","requested_username":"DELTA","role":"service_role"}']);
  await as(D, 'select complete_user_profile()');
  assert.deepEqual((await as(D, 'select language,workout_sharing,share_workout_notes from user_preferences')).rows[0], { language: 'en', workout_sharing: true, share_workout_notes: false });
  assert.equal((await as(D, 'select username from user_profiles where user_id=$1', [D])).rows[0].username, 'delta');
  assert.equal((await as(D, 'select id from workouts')).rows.length, 0, 'untrusted signup metadata never grants another user’s records');
  await assert.rejects(as(null, 'select * from user_preferences'), /permission/);
  await assert.rejects(as(null, "select complete_user_profile('intruder')"), /permission/);
  assert.equal((await as(null, "select username_available('ALPHA_RENAMED') available")).rows[0].available, false);
  await db.exec('reset role');
  const functions = (await db.query("select proname,proconfig,has_function_privilege('anon',oid,'execute') anon from pg_proc where proname in ('complete_user_profile','normalize_profile_username')")).rows;
  assert.ok(functions.every(row => row.proconfig?.includes('search_path=\"\"') && row.anon === false));
  await db.transaction(async tx => tx.exec(fs.readFileSync(migration, 'utf8')));
  const defs = (await db.query("select column_default from information_schema.columns where table_name='user_preferences' and column_name='language'")).rows[0];
  assert.match(defs.column_default, /it/);
  // Simulate an inconsistent legacy installation: collisions must abort the migration, never rename identities.
  await db.exec("drop trigger normalize_profile_username on user_profiles; alter table user_profiles drop constraint user_profiles_username_lowercase; drop index user_profiles_username_ci;");
  await db.query("update user_profiles set username='ALPHA_RENAMED' where user_id=$1", [B]);
  after = (await db.query('select user_id,username from user_profiles order by user_id')).rows;
  await assert.rejects(db.transaction(async tx => tx.exec(fs.readFileSync(migration, 'utf8'))), /case-insensitive username collisions/);
  assert.deepEqual((await db.query('select user_id,username from user_profiles order by user_id')).rows, after);
  assert.equal(normalizeUsername('  Ale_123  '), 'ale_123');
  console.log('PASS Settings identity: lowercase backfill/write normalization, collision abort, repeat-safe migration, IDs/avatar preservation, Italian default, saved English/opt-out preserved, A/B/anon RLS and legacy case-insensitive lookup');
} finally { await db.close(); }
