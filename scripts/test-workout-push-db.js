import assert from 'node:assert/strict';
import { applyCommunityMigration } from '../tests/workout/communityDatabase.js';
import { createProfileUpgradeDatabase } from '../tests/workout/profileUpgradeDatabase.js';
const db = await createProfileUpgradeDatabase();
const A = '11111111-1111-4111-8111-111111111111', B = '22222222-2222-4222-8222-222222222222';
try {
  await db.exec('alter table auth.users add email_confirmed_at timestamptz,add raw_user_meta_data jsonb;');
  for (const suffix of ['training_profile_upgrade', 'username_only_cleanup', 'training_active_identity_media']) await applyCommunityMigration(db, suffix);
  await applyCommunityMigration(db, 'workout_web_push');
  await db.exec(`insert into auth.users(id) values('${A}'),('${B}');`);
  const as = async (id, sql) => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]); await db.exec('set role authenticated'); return db.query(sql); };
  const workout = (await as(A, "insert into workouts(name) values('QA') returning id")).rows[0].id;
  const add = async n => (await as(A, `insert into workout_sets(workout_id,exercise,set_number,weight,reps) values('${workout}','Bench',${n},50,8) returning id`)).rows[0].id;
  await add(1);
  assert.equal((await as(A, 'select id from workout_rest_timers')).rows.length, 0);
  await as(A, 'insert into workout_web_rest_preferences(enabled,seconds,notifications) values(true,120,false)');
  const first = await add(2);
  let timers = (await as(A, 'select id,user_id,workout_id,set_id,scheduled_for,expires_at,state,created_at from workout_rest_timers')).rows;
  assert.equal(timers.length, 1); assert.equal(timers[0].set_id, first);
  assert.equal(Date.parse(timers[0].expires_at) - Date.parse(timers[0].scheduled_for), 300000);
  const second = await add(3);
  timers = (await as(A, 'select id,user_id,workout_id,set_id,scheduled_for,expires_at,state,created_at from workout_rest_timers order by created_at,id')).rows;
  assert.equal(timers.filter(t => t.state === 'queued').length, 1);
  assert.equal(timers.find(t => t.state === 'queued').set_id, second);
  assert.equal((await as(B, 'select id from workout_rest_timers')).rows.length, 0);
  await assert.rejects(as(B, `insert into workout_web_rest_preferences(user_id) values('${A}')`), /row-level|duplicate/);
  await as(A, 'update workout_web_rest_preferences set enabled=false');
  assert.equal((await as(A, "select id from workout_rest_timers where state='queued'")).rows.length, 0);
  await as(A, 'update workout_web_rest_preferences set enabled=true');
  await add(4);
  await as(A, `update workouts set ended_at=now() where id='${workout}'`);
  assert.equal((await as(A, "select id from workout_rest_timers where state='queued'")).rows.length, 0);
  await add(5);
  assert.equal((await as(A, 'select id from workout_rest_timers')).rows.length, 3, 'historical inserts never schedule');
  await db.exec('reset role');
  const live = (await as(A, "insert into workouts(name) values('Failure QA') returning id")).rows[0].id;
  const beforeFailure = (await as(A, `insert into workout_sets(workout_id,exercise,set_number,weight,reps) values('${live}','Curl',76,0,10) returning id`)).rows[0].id;
  await db.exec('reset role');
  await db.exec(`create function public.qa_fail_timer() returns trigger language plpgsql as $$begin raise exception 'QA fault';end$$;
    create trigger qa_fail before insert on workout_rest_timers for each row execute function qa_fail_timer();`);
  await as(A, `insert into workout_sets(workout_id,exercise,set_number,weight,reps) values('${live}','Curl',77,0,10)`);
  assert.equal((await as(A, `select * from workout_sets where workout_id='${live}'`)).rows.length, 2, 'timer failure must not lose set');
  assert.equal((await as(A, `select state from workout_rest_timers where set_id='${beforeFailure}'`)).rows[0].state, 'cancelled', 'failed replacement must not leave the previous reminder armed');
  await db.exec('reset role; drop trigger qa_fail on workout_rest_timers;');
  await as(A, 'update workout_web_rest_preferences set notifications=true');
  const last = (await as(A, `insert into workout_sets(workout_id,exercise,set_number,weight,reps,is_warmup) values('${live}','Curl',1001,10,8,true) returning id`)).rows[0].id;
  await db.exec('reset role');
  await db.query("update workout_rest_timers set scheduled_for=now()-interval '1 second' where set_id=$1",[last]);
  await db.exec('set role service_role');
  assert.equal((await db.query('select * from claim_workout_web_rest()')).rows.length,0,'no subscription means no delivery claim');
  await db.exec('reset role');
  await db.query("insert into workout_push_subscriptions(user_id,endpoint,subscription) values($1,'https://fcm.googleapis.com/fixture','{}')",[A]);
  for (let i=0;i<4;i++) await db.query('insert into workout_push_subscriptions(user_id,endpoint,subscription) values($1,$2,$3)',[A,`https://fcm.googleapis.com/fixture-${i}`,'{}']);
  await assert.rejects(db.query("insert into workout_push_subscriptions(user_id,endpoint,subscription) values($1,'https://fcm.googleapis.com/extra','{}')",[A]), /Maximum five/);
  await db.query("update workout_rest_timers set scheduled_for=now()-interval '1 second' where set_id=$1", [last]);
  await db.exec('set role service_role');
  const claimed = (await db.query('select * from claim_workout_web_rest()')).rows;
  assert.equal(claimed.length, 1); assert.equal(claimed[0].set_id, last);
  assert.equal((await db.query('select * from claim_workout_web_rest()')).rows.length, 0, 'claim is idempotent');
  await db.exec('reset role');
  await db.query("update workout_rest_timers set state='sent' where set_id=$1", [last]);
  await as(A, `insert into workout_sets(workout_id,exercise,set_number,weight,reps) values('${live}','Curl',2,10,8)`);
  assert.equal((await as(A, `select state from workout_rest_timers where set_id='${last}'`)).rows[0].state, 'cancelled', 'new set invalidates accepted but delayed push');
  await as(A, 'update workout_web_rest_preferences set notifications=false');
  await db.exec('reset role');
  assert.equal((await db.query("select delivery_enabled from workout_rest_timers where workout_id=$1 and state='queued'", [live])).rows[0].delivery_enabled, false);
  await as(A, 'update workout_web_rest_preferences set notifications=true');
  await db.exec('reset role');
  assert.equal((await db.query("select delivery_enabled from workout_rest_timers where workout_id=$1 and state='queued'", [live])).rows[0].delivery_enabled, false, 're-enabling notifications never resurrects an old alert');
  await as(A, `select cancel_workout_web_rest('${live}')`);
  await as(A, `insert into workout_sets(workout_id,exercise,set_number,weight,reps) values('${live}','Curl',3,10,8)`);
  await db.exec('reset role');
  await db.query("update workout_rest_timers set scheduled_for=now()-interval '10 minutes',expires_at=now()-interval '5 minutes' where workout_id=$1 and state='queued'",[live]);
  await db.exec('set role service_role');
  assert.equal((await db.query('select * from claim_workout_web_rest()')).rows.length,0,'stale alerts are never claimed');
  await db.exec('reset role');
  assert.equal((await db.query("select count(*)::int n from workout_rest_timers where workout_id=$1 and state='expired'",[live])).rows[0].n,1);
  await as(A, `delete from workouts where id='${live}'`);
  assert.equal((await as(A, `select id from workout_rest_timers where workout_id='${live}'`)).rows.length, 0);
  await db.exec('reset role');
  assert.equal((await db.query("select count(*)::int n from brain_outbox_messages where source_type='workout_rest_timer' and status in ('queued','claimed')")).rows[0].n, 0);
  await assert.rejects(as(A, 'select delivery_token from workout_rest_timers'), /permission/);
  await assert.rejects(as(A, 'select * from claim_workout_web_rest()'), /permission/);
  await db.exec('reset role; set role anon');
  await assert.rejects(db.query('select * from workout_web_rest_preferences'), /permission/);
  console.log('PASS PostgreSQL rest timer: OFF, schedule, replace, owner RLS, disable, end, historical isolation, fail-open, warmups, idempotent claims, delayed-token revocation, secret grants, anon');
} finally { await db.close(); }
