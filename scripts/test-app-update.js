let connected=true;
const manager=createAppUpdateManager({serviceWorker:sw,online:()=>connected,storage,buildId:'A',fetchVersion:async()=>'B',reload:()=>reloads++});
let notifications=0;manager.subscribe(()=>notifications++);
await Promise.all([manager.check(),manager.check(),manager.check()]);
assert.equal(calls,1);assert.equal(manager.getSnapshot().available,true);assert.ok(notifications>0);
manager.dismiss();assert.ok(manager.getSnapshot().dismissedUntil>Date.now());
manager.setGuard(()=>'active-workout');assert.equal(await manager.apply(),false);assert.equal(skip,0);
manager.setGuard(()=>'unsaved-work');assert.equal(await manager.apply(),false);assert.equal(skip,0);
manager.setGuard(()=>null);assert.equal(await manager.apply(),true);assert.equal(skip,1);assert.equal(reloads,1);
assert.equal(manager.getSnapshot().status,'loading');
const next=createAppUpdateManager({serviceWorker:sw,online:()=>true,storage,buildId:'B',fetchVersion:async()=>'B',reload:()=>{}});
next.confirm();assert.equal(next.getSnapshot().status,'confirmed');
reg.waiting=null;await next.check();assert.equal(next.getSnapshot().status,'current');
connected=false;await manager.check();assert.equal(manager.getSnapshot().status,'offline');
connected=true;reg.update=async()=>{throw new Error('network');};await manager.check();assert.equal(manager.getSnapshot().status,'error');
assert.equal(values.has('lifeos:training:v1:a:draft:s'),true);
console.log('PASS update deduplication, shared state, Later, active/dirty guards, activation, actual-version confirmation, current/offline/failure and exercise baselines');
