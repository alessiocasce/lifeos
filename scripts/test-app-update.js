import assert from 'node:assert/strict';
import { createAppUpdateManager } from '../src/utils/appUpdateManager.js';
import { emptySetDraft, withDraftBaseline, draftHasEdits, writeWorkoutDraft, readExerciseDraft, hasWorkoutDraftEdits } from '../src/utils/workoutContinuity.js';

const values = new Map();
const storage = {getItem:key=>values.get(key)||null,setItem:(key,value)=>values.set(key,value),removeItem:key=>values.delete(key)};
const draft = withDraftBaseline({...emptySetDraft(),exercise:'Curl',weight:'55',reps:'8'});
assert.equal(draftHasEdits(draft),false);
assert.equal(draftHasEdits({...draft,weight:'60'}),true);
writeWorkoutDraft('a','s',{...draft,notes:'Changed'},{storage});
writeWorkoutDraft('a','s',withDraftBaseline({...draft,exercise:'Row'}),{storage});
assert.equal(hasWorkoutDraftEdits('a','s',{storage}),true);
assert.equal(readExerciseDraft('a','s',{exercise:'Curl'},{storage}).notes,'Changed');
assert.equal(hasWorkoutDraftEdits('b','s',{storage}),false);
const sw = new EventTarget(); let calls=0; let reloads=0; let skip=0;
const reg = new EventTarget();
reg.update=async()=>{calls++;};
reg.waiting={postMessage(){skip++;sw.dispatchEvent(new Event('controllerchange'));}};
